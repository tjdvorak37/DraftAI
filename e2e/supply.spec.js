import { test,expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';

test('yard tag, staged stock, ordering and counted receiving work on desktop and mobile',async({page})=>{
  test.setTimeout(360000);
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  expect((await page.request.post('/api/auth/login',{data:{email:'studio@example.test',password:'isolated-test-password'}})).ok()).toBe(true);
  const post=async(path,data)=>{const response=await page.request.post(`/api${path}`,{data});const result=await response.json();expect(response.ok(),JSON.stringify(result)).toBe(true);return result;};
  await post('/inventory',{id:'E2E-YARD',name:'Yard ready frame',category:'Steel',unit:'ea',stock:10,price:null,reorder:8,location:'Plant floor',supplier:'Yard Vendor',location_id:'MAIN'});
  const customer=await post('/customers',{name:'Yard Test Customer',accountNumber:'YARD-100',contactName:'Yard Contact',phone:'555-0104',billingAddress:{},shippingAddress:{line1:'100 Delivery Road',city:'Audubon',region:'IA',postalCode:'50025',country:'US'},shippingInstructions:'Call site contact before unloading.'});
  const order=await post('/shipments',{requestKey:randomUUID(),kind:'customer',sourceLocation:'MAIN',customerId:customer.id,reference:'SO-YARD-100',lines:[{partId:'E2E-YARD',quantity:6}]});
  await post(`/shipments/${order.id}/action`,{action:'hold',revision:1});
  await page.goto('/');
  await page.getByRole('navigation',{name:'Workspace'}).getByRole('button',{name:'Shipping',exact:true}).click();
  await page.getByRole('textbox',{name:'Search shipments'}).fill('SO-YARD-100');
  await page.getByRole('button',{name:'Open order'}).click();
  await page.getByRole('textbox',{name:'Yard position'}).fill('North Yard / Row B / Bay 12');
  page.once('dialog',dialog=>dialog.accept());
  await page.getByRole('button',{name:'Stage in yard',exact:true}).click();
  await expect(page.getByText('Staged at North Yard',{exact:false})).toBeVisible();
  await page.getByRole('button',{name:'Print yard tag',exact:true}).click();
  await expect(page.locator('.yard-tag-preview')).toContainText('Yard Test Customer');
  await expect(page.locator('.yard-tag-preview')).toContainText('SO-YARD-100');
  await expect(page.locator('.yard-tag-preview')).toContainText('North Yard / Row B / Bay 12');
  await expect(page.locator('.yard-tag-preview')).toContainText('555-0104');
  await page.emulateMedia({media:'print'});
  await expect(page.locator('.yard-print-root')).toBeVisible();
  await expect(page.locator('.app-shell')).not.toBeVisible();
  await page.screenshot({path:'/tmp/accusteel-yard-tag.png',fullPage:true});
  const pdf=await page.pdf({path:'/tmp/accusteel-yard-tag.pdf',printBackground:true});expect(pdf.length).toBeGreaterThan(5000);
  await page.emulateMedia({media:'screen'});
  await page.getByRole('button',{name:'Close dialog',exact:true}).last().click();
  await page.getByRole('button',{name:'Close dialog',exact:true}).click();
  await page.getByRole('navigation',{name:'Workspace'}).getByRole('button',{name:'Inventory',exact:true}).click();
  await page.getByRole('textbox',{name:'Search inventory'}).fill('E2E-YARD');
  const stock=page.locator('.inventory-table tbody tr');
  await expect(stock.locator('td').nth(2)).toContainText('10');
  await expect(stock.locator('td').nth(3)).toHaveText('0');
  await expect(stock.locator('td').nth(4)).toHaveText('6');
  await expect(stock.locator('td').nth(5)).toHaveText('4');
  await page.getByRole('navigation',{name:'Workspace'}).getByRole('button',{name:'Ordering',exact:true}).click();
  await page.getByRole('textbox',{name:'Search supply orders'}).fill('E2E-YARD');
  await page.getByRole('button',{name:'Prepare order',exact:true}).click();
  await page.getByRole('textbox',{name:'Supplier / PO reference',exact:true}).fill('PO-YARD-100');
  await expect(page.getByRole('spinbutton',{name:'Purchase quantity 1'})).toHaveValue('4');
  await page.getByRole('button',{name:'Save purchase draft',exact:true}).click();
  await page.getByRole('button',{name:'Purchase drafts',exact:true}).click();
  await page.getByRole('textbox',{name:'Search supply orders'}).fill('PO-YARD-100');
  await page.getByRole('button',{name:'Open purchase',exact:true}).click();
  page.once('dialog',dialog=>dialog.accept());
  await page.getByRole('button',{name:'Mark as ordered',exact:true}).click();
  await expect(page.getByRole('button',{name:'Count received materials',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Close dialog',exact:true}).click();
  await page.getByRole('navigation',{name:'Workspace'}).getByRole('button',{name:'Receiving',exact:true}).click();
  await page.getByRole('textbox',{name:'Search supply orders'}).fill('PO-YARD-100');
  await page.getByRole('button',{name:'Open purchase',exact:true}).click();
  await page.getByRole('button',{name:'Count received materials',exact:true}).click();
  await expect(page.getByRole('button',{name:'Approve and add to inventory',exact:true})).toBeDisabled();
  await expect(page.getByRole('spinbutton',{name:'Accepted E2E-YARD'})).toHaveValue('');
  await page.getByRole('spinbutton',{name:'Accepted E2E-YARD'}).fill('3');
  await page.getByRole('spinbutton',{name:'Rejected E2E-YARD'}).fill('1');
  await page.getByRole('textbox',{name:'Receiving bin E2E-YARD'}).fill('North Rack 2');
  await page.getByRole('checkbox',{name:'Approve counted materials'}).check();
  const approval=page.waitForRequest(request=>request.url().endsWith('/receive')&&request.method()==='POST');
  await page.getByRole('button',{name:'Approve and add to inventory',exact:true}).click();
  const request=await approval;
  await expect(page.getByText('Receipt history',{exact:true})).toBeVisible();
  const replay=await page.request.post(request.url(),{data:request.postDataJSON()});expect((await replay.json()).alreadyApplied).toBe(true);
  await expect(page.getByText('E2E-YARD: accepted 3, rejected 1',{exact:false})).toBeVisible();
  await page.getByRole('button',{name:'Count received materials',exact:true}).click();
  await page.getByRole('spinbutton',{name:'Accepted E2E-YARD'}).fill('1');
  await page.getByRole('checkbox',{name:'Approve counted materials'}).check();
  await page.getByRole('button',{name:'Approve and add to inventory',exact:true}).click();
  await expect(page.getByRole('button',{name:'Count received materials',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Close dialog',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('navigation',{name:'Workspace'}).getByRole('button',{name:'Ordering',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Ordering board',exact:true})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'/tmp/accusteel-ordering-mobile.png',fullPage:true});
  const inventory=await(await page.request.get('/api/inventory')).json();const final=inventory.find(item=>item.id==='E2E-YARD');expect(final.stock).toBe(14);expect(final.staged).toBe(6);expect(final.available).toBe(8);
  expect(errors).toEqual([]);
});